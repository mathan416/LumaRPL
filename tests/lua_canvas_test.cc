#include "lua_canvas.h"
#include "input.h"
#include <cassert>
#include <cstring>
#include <cstdio>
const pattern pattern::black=pattern(0,0,0);
const pattern pattern::white=pattern(255,255,255);
const pattern pattern::invert=pattern(~0ULL);
#include "rgb332_patterns.h"
int main()
{
    alignas(8) unsigned char buffer[320*320*BITS_PER_PIXEL/8+16];memset(buffer,0xa5,sizeof buffer);
    surface screen(reinterpret_cast<pixword *>(buffer+8),320,320,320,320);int a[6]={};
    pico_lua_canvas(screen,PICO_LUA_CLEAR,a,pattern::black);
    a[0]=0;a[1]=0;pico_lua_canvas(screen,PICO_LUA_PIXEL,a,pattern(255,0,0));
    uint8_t rgb[3];pico_rgb_pixel(buffer+8,0,0,rgb);assert(rgb[0]==255&&!rgb[1]&&!rgb[2]);
    a[0]=20;a[1]=35;a[2]=110;a[3]=70;a[4]=0;pico_lua_canvas(screen,PICO_LUA_RECT,a,pattern(255,160,0));
    a[0]=220;a[1]=110;a[2]=40;a[4]=1;pico_lua_canvas(screen,PICO_LUA_CIRCLE,a,pattern(0,255,0));
    pico_rgb_pixel(buffer+8,220,110,rgb);assert(!rgb[0]&&rgb[1]==255&&!rgb[2]);
    a[0]=-4096;a[1]=-4096;a[2]=4096;a[3]=4096;pico_lua_canvas(screen,PICO_LUA_LINE,a,pattern(0,200,255));
    // Optional RGB preview generated by the actual native drawing helper.
    FILE *f=fopen("build/lua-canvas-test.ppm","wb");assert(f);fprintf(f,"P6\n320 320\n255\n");
    for(int y=0;y<320;++y)for(int x=0;x<320;++x){pico_rgb_pixel(buffer+8,x,y,rgb);assert(fwrite(rgb,1,3,f)==3);}fclose(f);
    a[0]=-4096;a[1]=4096;a[2]=640;a[4]=1;pico_lua_canvas(screen,PICO_LUA_CIRCLE,a,pattern::white);
    a[0]=160;a[1]=160;pico_lua_canvas(screen,PICO_LUA_CIRCLE,a,pattern::white);
    a[0]=-10;a[1]=-10;a[2]=0;a[3]=640;pico_lua_canvas(screen,PICO_LUA_RECT,a,pattern::white);
    for(int i=0;i<8;++i)assert(buffer[i]==0xa5&&buffer[320*320*BITS_PER_PIXEL/8+8+i]==0xa5);
    puts("PASS: actual colour Lua canvas primitives, colours, zero-size shapes and extreme clipping");
}
