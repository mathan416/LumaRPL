#!/usr/bin/env python3
"""Flash-resident complete editor examples, derived from the language references."""
from pathlib import Path
import argparse,json
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
rpl=[dict(title=e['title'],source='«\n'+e['source']+'\n»',expected=e['expected']) for e in json.loads((root/'docs/help/examples.json').read_text())[:4]]
rows=[]
for language,entries in [(0,rpl),(1,[e for e in json.loads((root/'docs/help/chip8-reference.json').read_text()) if e['example_kind']=='program']),(2,json.loads((root/'docs/help/lua-reference.json').read_text()))]:
 for e in entries:
  rows.append(dict(language=language,title=e.get('title',e.get('name')),source=e['source'],expected=e['expected']))
lines=['// Generated by tools/generate_editor_examples.py. GPL-3.0.','#pragma once','namespace pico_editor_examples {','struct Example {unsigned language;const char *title,*source,*expected;};','inline constexpr Example entries[]={']
assert all(0<len(e['source'].encode())<16384 for e in rows)
assert all(len(e['source'].encode())+len(e['expected'].encode())+256<1024 for e in rows)
assert all(sum(e['language']==language for e in rows)<=48 for language in range(3))
for e in rows:lines.append('{'+str(e['language'])+','+','.join(json.dumps(e[k],ensure_ascii=False) for k in ('title','source','expected'))+'},')
lines+=['};','}'];text='\n'.join(lines)+'\n';path=root/'pico/ui/editor_examples.h'
if args.check:assert path.read_text()==text
else:path.write_text(text)
print('PASS:',len(rows),'complete editor examples generated from tested help sources')
