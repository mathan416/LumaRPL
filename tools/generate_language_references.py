#!/usr/bin/env python3
"""Build bounded SD reference books for the supported Lua and CHIP-8 interfaces."""
from pathlib import Path
import argparse,json,struct,zlib
root=Path(__file__).resolve().parents[1];p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
navigation=json.loads((root/'docs/help/language-navigation.json').read_text())
header='// Generated by tools/generate_language_references.py. GPL-3.0.\n#pragma once\n#include "reference_data.h"\nnamespace pico_reference_data {\n'
for book in ('lua','chip8'):
 rows=json.loads((root/'docs/help'/f'{book}-reference.json').read_text());cats=navigation[book];assert set(cats)=={r['category'] for r in rows};rows.sort(key=lambda r:(cats.index(r['category']),r['name'].casefold() if r['category']=='Instruction reference' else ''));index=bytearray();data=bytearray();names=set();assert len(cats)<=32
 for row in rows:
  assert row['name'] not in names;names.add(row['name']);assert row['source'] and row['expected']
  body=row['text']
  if row.get('steps'):body+='\n\n'+'\n'.join(str(i+1)+'. '+step for i,step in enumerate(row['steps']))
  if row.get('signature'):body+='\n\nUsage\n'+row['signature']
  label='Instruction fragment' if row['example_kind']=='snippet' else 'Complete program' if row['example_kind']=='program' else 'Example script'
  body+='\n\n'+label+'\n'+row['source']+'\n\n'+row['expected']
  if row.get('after'):body+='\n\n'+row['after']
  text=body.encode();title=row.get('title',row['name']).encode();keys=('\x1f'+'\x1f'.join(dict.fromkeys([row['name'],row.get('title',row['name'])]))+'\x1f').encode()
  assert len(title)<64 and len(keys)<384 and 0<len(text)<=4096
  index+=struct.pack('<IHBBI64s384s',len(data),len(text),cats.index(row['category']),0,zlib.crc32(text),title,keys);data+=text
 header+=f'inline constexpr Category {book}_categories[]={{\n'
 for cat in cats:
  ids=[i for i,r in enumerate(rows) if r['category']==cat];header+='{'+json.dumps(cat)+','+str(ids[0])+','+str(len(ids))+'},\n'
 header+='};\n'
 for ext,content in [('lri',struct.pack('<4sIII',b'LRH1',len(rows),len(data),460)+index),('lrt',data)]:
  path=root/'resources/help'/f'{book}.{ext}'
  if args.check:assert path.read_bytes()==content,path
  else:path.write_bytes(content)
 print(f'PASS: {book}: {len(rows)} pages, each with an example and expected behavior')
header+='}\n';path=root/'pico/ui/language_reference_data.h'
if args.check:assert path.read_text()==header
else:path.write_text(header)
