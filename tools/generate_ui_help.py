#!/usr/bin/env python3
"""Generate flash-only PicoCalc reference and menu explanations from reviewed text."""
from pathlib import Path
import argparse,json
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
menus=json.loads((root/'docs/ui/menu-help.json').read_text());topics=json.loads((root/'docs/ui/reference.json').read_text())
tool_help=json.loads((root/'docs/ui/tool-help.json').read_text())
registered={s['id'] for s in json.loads((root/'pico/ui/screens.json').read_text()) if s['kind']=='menu'}
assert registered==menus.keys(),{'missing':sorted(registered-menus.keys()),'unknown':sorted(menus.keys()-registered)}
q=lambda v:json.dumps(v,ensure_ascii=False)
lines=['// Generated by tools/generate_ui_help.py; edit docs/ui/*.json. GPL-3.0.','#pragma once','#include <cstring>','#include <cstdio>','namespace pico_ui_help {','struct Menu {const char *id,*overview;};','struct Item {const char *id;unsigned row;const char *text;};','inline constexpr Menu menus[]={']
for id,m in menus.items():
 assert m['overview'].strip()
 assert 255+4+len(m['overview'])+max([len(t) for t in m['items'].values()]+[0])<1024,('Details capacity',id)
 lines.append('{'+q(id)+','+q(m['overview'])+'},')
lines+=['};','inline constexpr Item items[]={']
for id,m in menus.items():
 for row,text in m['items'].items():lines.append('{'+q(id)+','+row+','+q(text)+'},')
lines+=['};','struct Topic {const char *title,*text;};','inline constexpr Topic topics[]={']
for t in topics:lines.append('{'+q(t['title'])+','+q(t['text'])+'},')
lines+=['};','struct Tool {const char *id,*title,*text;};','inline constexpr Tool tools[]={']
for id,t in tool_help.items():
 assert len(t['text'])>100
 lines.append('{'+q(id)+','+q(t['title'])+','+q(t['text'])+'},')
lines+=['};',r'''inline const char *tool_text(const char *id)
{for(const auto &t:tools)if(!strcmp(t.id,id))return t.text;return "";}
inline const Menu *context(const char *id)
{if(id)for(const auto &m:menus)if(!strcmp(m.id,id))return &m;return nullptr;}
inline bool describe(const char *id,unsigned row,const char *label,char *out,size_t capacity)
{
    const Menu *menu=context(id);if(!menu){if(capacity)out[0]=0;return false;}
    const char *detail=nullptr;for(const auto &item:items)if(item.row==row&&!strcmp(item.id,id)){detail=item.text;break;}
    // The complete selected value remains available even if its menu label was elided.
    int n=detail?snprintf(out,capacity,"%s\n\n%s\n\n%s",label,detail,menu->overview):snprintf(out,capacity,"%s\n\n%s",label,menu->overview);
    return n>=0&&size_t(n)<capacity;
}
}''']
text='\n'.join(lines)+'\n';target=root/'pico/ui/help_data.h'
manual='# LumaRPL calculator reference for PicoCalc\n\n'+ '\n\n'.join('## '+t['title']+'\n\n'+t['text'] for t in topics)+'\n'
manual_path=root/'resources/help/LumaRPL.md'
if args.check:
 assert target.read_text()==text,'Regenerate help_data.h'
 assert manual_path.read_text()==manual,'Regenerate SD reference'
else:
 target.write_text(text);manual_path.parent.mkdir(exist_ok=True);manual_path.write_text(manual)
print(f'PASS: {len(menus)} menu contexts, {sum(len(m["items"]) for m in menus.values())} action explanations, {len(topics)} reference topics; {len(tool_help)} tool help pages')
