#!/usr/bin/env python3
"""Reference-only extension of the existing compact font; native Help font is unchanged."""
from pathlib import Path
import re,argparse
root=Path(__file__).resolve().parents[1];p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
source=(root/'pico/HeaderFont.cc').read_text().split('byte(uint(object::ID_sparse_font) >> 7),',1)[1]
data=bytes(int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]{2})',source));position=0
def take():
 global position
 value=0;shift=0
 while True:
  byte=data[position];position+=1;value|=(byte&127)<<shift
  if byte<128:return value
  shift+=7
size=take();height=take();assert height==13
records={}
while True:
 first,count=take(),take()
 if first==count==0:break
 for cp in range(first,first+count):
  start=position;x,y,w,h,advance=[take() for _ in range(5)];position+=(w*h+7)//8;records[cp]=data[start:position]
def leb(n):
 out=bytearray()
 while n>=128:out.append((n&127)|128);n>>=7
 out.append(n);return bytes(out)
def glyph(cp,rows,y=2,advance=8):
 assert cp not in records
 width=len(rows[0]) if rows else 0;pixels=bytearray((width*len(rows)+7)//8)
 for row,line in enumerate(rows):
  assert len(line)==width
  for x,c in enumerate(line):
   if c=='1':bit=row*width+width-1-x;pixels[bit//8]|=1<<(bit%8)
 records[cp]=b''.join(map(leb,[0,y,width,len(rows),advance]))+pixels
patterns={
0x2115:['1100011','1110011','1110011','1101011','1101011','1100111','1100111','1100011','1100011'],
0x2124:['1111111','0000011','0000110','0001100','0011000','0110000','1100000','1100000','1111111'],
0x24d2:['0011100','0100010','1000001','1001101','1010001','1010001','1001101','0100010','0011100'],
0x2153:['0100000','1100001','0100010','0100100','0001000','0010000','0100110','1000001','0000010','0000001','0000110'],
0x226a:['0010010','0100100','1001000','0100100','0010010'],
0x21d2:['0001000','0000100','1111110','0000001','1111110','0000100','0001000'],
0x2205:['0011101','0100010','1000111','1001001','1110001','0100010','1011100'],
0x26a0:['0001000','0010100','0010100','0101010','0101010','1000001','1001001','1111111']}
for cp,rows in patterns.items():glyph(cp,rows)
small={0x209b:['011','100','010','001','110'],0x209a:['110','101','110','100','100'],0x2093:['101','101','010','101','101'],0x1d67:['101','101','011','001','010'],0x2091:['010','101','111','100','011'],0x2099:['110','101','101','101','101'],0x1d62:['010','000','110','010','111']}
for cp,rows in small.items():glyph(cp,rows,y=8,advance=4)
glyph(0x207a,['010','111','010'],y=1,advance=4);glyph(0x2e3,['101','101','010','101','101'],y=1,advance=4)
for cp,advance in [(0x202f,3),(0xfe0f,0),(0x200b,0)]:glyph(cp,[],y=0,advance=advance)
body=leb(height)
assert max(records)<=0xffff
items=sorted(records.items());i=0
while i<len(items):
 start=i
 while i+1<len(items) and items[i+1][0]==items[i][0]+1:i+=1
 body+=leb(items[start][0])+leb(i-start+1)+b''.join(record for cp,record in items[start:i+1]);i+=1
body+=b'\0\0'+leb(len('PicoReferenceFont'))+b'PicoReferenceFont'
payload=leb(len(body))+body
lines=['// Generated by tools/generate_reference_font.py. Base: FogSans compact; additions: LumaRPL mathematical glyphs. GPL-3.0.','#include "font.h"','#include "target.h"','#include "object.h"','extern const unsigned char PicoReferenceFont_sparse_font_data[];','const unsigned char PicoReferenceFont_sparse_font_data[] FONT_QSPI = {','byte(object::ID_sparse_font) | 0x80, byte(uint(object::ID_sparse_font) >> 7),']
lines+= [','.join(f'0x{b:02x}' for b in payload[i:i+20])+',' for i in range(0,len(payload),20)];lines+=['};','']
result='\n'.join(lines);target=root/'pico/ReferenceFont.cc'
if args.check:assert target.read_text()==result
else:target.write_text(result)
print('PASS: reference font:',len(payload)+2,'flash bytes;',len(records),'glyphs; native compact font unchanged')
