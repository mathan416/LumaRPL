#!/usr/bin/env python3
"""Compact fixed-cell source font: Pixel Operator Mono, with bounded RPL glyph supplements."""
from pathlib import Path
import argparse,re,subprocess,shutil
root=Path(__file__).resolve().parents[1];p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();out=root/'build/source-font';out.mkdir(parents=True,exist_ok=True)
source=(root/'db48x/tools/ttf2font/ttf2font.cpp').read_text();assert source.count('colsGlyph += colsBeforeGlyph;')==1
source=source.replace('colsGlyph += colsBeforeGlyph;','/* Preserve sparse right edge with negative left bearing. */');(out/'generator.cc').write_text(source)
flags=subprocess.check_output(['pkg-config','--cflags','--libs','freetype2'],text=True).split() if shutil.which('pkg-config') else ['-I/opt/homebrew/opt/freetype/include/freetype2','-L/opt/homebrew/opt/freetype/lib','-lfreetype']
subprocess.run(['clang++','-std=c++17','-I'+str(root/'db48x/src'),str(out/'generator.cc'),*flags,'-o',str(out/'ttf2font')],check=True)
subprocess.run([str(out/'ttf2font'),'-s','14','PicoSourceFont','db48x/fonts/PixelOperatorMono.ttf',str(out/'base.cc')],cwd=root,check=True)
def read(path):
 data=bytes(int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]{2})',path.read_text().split('byte(uint(object::ID_sparse_font) >> 7),',1)[1]));pos=0
 def take():
  nonlocal pos
  value=shift=0
  while True:
   b=data[pos];pos+=1;value|=(b&127)<<shift
   if b<128:return value
   shift+=7
 take();height=take();glyphs={}
 while True:
  first,count=take(),take()
  if first==count==0:break
  for cp in range(first,first+count):
   x,y,w,h,advance=[take() for _ in range(5)];bits=data[pos:pos+(w*h+7)//8];pos+=len(bits);glyphs[cp]=(x,y,w,h,advance,bits)
 return height,glyphs
height,base=read(out/'base.cc');fallback_height,fallback=read(root/'pico/HeaderFont.cc');assert height==14 and fallback_height==13
records={}
def leb(v):
 b=bytearray()
 while v>=128:b.append((v&127)|128);v>>=7
 b.append(v);return b
for cp,g in {**fallback,**base}.items():
 x,y,w,h,advance,bits=g
 # Mono glyphs are fitted to the fixed cell. Additional mathematical glyphs are reduced
 # to fit the cell; OR coverage keeps thin strokes instead of dropping them.
 original=cp in base
 nw=min(w,6);nh=min(h,12);nx=min(x,6-nw);ny=min(round(y*12/height) if original else y,12-nh)
 if not original:ny=min(round(y*12/13),12-nh)
 pixels=bytearray((nw*nh+7)//8)
 for row in range(h):
  for col in range(w):
   bit=row*w+w-1-col
   if bits[bit//8]&(1<<(bit%8)):
    r=min(nh-1,row*nh//h);c=min(nw-1,col*nw//w);b=r*nw+nw-1-c;pixels[b//8]|=1<<(b%8)
 records[cp]=b''.join(leb(v) for v in (nx,ny,nw,nh,7))+pixels
payload=leb(12)
for cp,data in sorted(records.items()):payload+=leb(cp)+leb(1)+data
payload+=b'\0\0';payload=leb(len(payload))+payload
text='// Generated by tools/generate_source_font.py. Pixel Operator Mono and existing LumaRPL RPL glyphs; see NOTICE.md.\n#include "font.h"\n#include "target.h"\n#include "object.h"\nextern const unsigned char PicoSourceFont_sparse_font_data[];\nconst unsigned char PicoSourceFont_sparse_font_data[] FONT_QSPI = {\nbyte(object::ID_sparse_font) | 0x80, byte(uint(object::ID_sparse_font) >> 7),\n'
text+='\n'.join(','.join('0x%02x'%b for b in payload[i:i+20])+',' for i in range(0,len(payload),20))+'\n};\n';target=root/'pico/SourceFont.cc'
if args.check:assert target.read_text()==text,'Regenerate source font'
else:target.write_text(text)
print('PASS: source font:',len(records),'glyphs, 7x12 cells,',len(payload)+2,'flash bytes')
