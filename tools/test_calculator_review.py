    diagnostics=result.stdout+result.stderr
    passed=passed and result.returncode in ((0,1) if error else (0,)) and not any(marker in diagnostics for marker in ('Assertion failed','AddressSanitizer','UndefinedBehaviorSanitizer','LeakSanitizer','runtime error:'))
    cases.append(dict(name=name,source=source,returncode=result.returncode,stdout=result.stdout.strip(),stderr=result.stderr.strip(),passed=passed))
    print(('PASS' if passed else 'FAIL'),name,flush=True)
